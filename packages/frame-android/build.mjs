// Builds and signs the frame APK with the plain SDK tools (no Gradle):
// javac -> d8 -> aapt2 (manifest, res/, frame-web's dist as assets) -> zipalign ->
// apksigner. `--test` only runs the JVM unit tests.
//
// The versionCode is the git commit count, which turbo's cache key does not see,
// so packages/frame-android/turbo.json turns caching off for this build.
//
// Needs JDK 17 and the Android SDK (build-tools 36.0.0, platform android-36);
// override locations with JAVA_17_HOME and ANDROID_SDK. The signing keystore
// lives in the git-ignored local/frame/ and is created on first build; keep it,
// because Android only installs updates signed with the same key.
import { execFileSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { readFrameConfig, toolPaths } from "./scripts/config.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../..");
const out = join(here, "build");
const { jdk: JDK, sdk: SDK } = toolPaths();
const TOOLS = join(SDK, "build-tools/36.0.0");
const ANDROID_JAR = join(SDK, "platforms/android-36/android.jar");
const PACKAGE_DIR = "dev/kidsdash/frame";

const run = (cmd, args, options = {}) =>
  execFileSync(cmd, args, { stdio: ["ignore", "inherit", "inherit"], ...options });
const java = (tool) => join(JDK, "bin", tool);
const sources = (dir) =>
  readdirSync(dir, { recursive: true })
    .filter((f) => f.endsWith(".java"))
    .map((f) => join(dir, f));

function writeConfig(dir, config) {
  const target = join(dir, PACKAGE_DIR);
  mkdirSync(target, { recursive: true });
  writeFileSync(
    join(target, "Config.java"),
    `package dev.kidsdash.frame;

/** Generated by build.mjs from frame.config.json. */
final class Config {
    static final String API_URL = ${JSON.stringify(config.apiUrl)};
    static final String KEY_ID = ${JSON.stringify(config.keyId)};
    static final String PUBLIC_KEY = ${JSON.stringify(config.publicKey)};

    private Config() {}
}
`,
  );
}

function test() {
  const classes = join(out, "test-classes");
  rmSync(classes, { recursive: true, force: true });
  // Only the classes with no Android dependencies are tested on the JVM.
  run(java("javac"), [
    "-d",
    classes,
    join(here, "src", PACKAGE_DIR, "ArtLibrary.java"),
    join(here, "src", PACKAGE_DIR, "Backlight.java"),
    join(here, "src", PACKAGE_DIR, "BundleVerifier.java"),
    join(here, "src", PACKAGE_DIR, "OutagePolicy.java"),
    join(here, "src", PACKAGE_DIR, "SleepSchedule.java"),
    join(here, "src", PACKAGE_DIR, "SlideshowPolicy.java"),
    join(here, "src", PACKAGE_DIR, "UpdatePolicy.java"),
    join(here, "src", PACKAGE_DIR, "SystemLog.java"),
    join(here, "src", PACKAGE_DIR, "WifiPower.java"),
    join(here, "src", PACKAGE_DIR, "TrimPolicy.java"),
    ...sources(join(here, "test")),
  ]);
  for (const suite of [
    "ArtLibraryTest",
    "BacklightTest",
    "BundleVerifierTest",
    "OutagePolicyTest",
    "SleepScheduleTest",
    "SlideshowPolicyTest",
    "TrimPolicyTest",
    "UpdatePolicyTest",
    "WifiPowerTest",
  ]) {
    run(java("java"), ["-cp", classes, `dev.kidsdash.frame.${suite}`]);
  }
}

function keystore() {
  const dir = join(root, "local/frame");
  const ks = join(dir, "frame-signing.p12");
  const passFile = join(dir, "frame-signing.pass");
  if (!existsSync(ks)) {
    mkdirSync(dir, { recursive: true, mode: 0o700 });
    writeFileSync(passFile, randomBytes(24).toString("base64url"), { mode: 0o600 });
    run(java("keytool"), [
      "-genkeypair",
      "-noprompt",
      "-keystore",
      ks,
      "-storetype",
      "PKCS12",
      "-storepass:file",
      passFile,
      "-alias",
      "frame",
      "-keyalg",
      "EC",
      "-groupname",
      "secp256r1",
      "-validity",
      "10000",
      "-dname",
      "CN=kids-dash frame",
    ]);
  }
  return { ks, passFile };
}

function version() {
  const git = (...args) => execFileSync("git", args, { cwd: root, encoding: "utf8" }).trim();
  return {
    code: git("rev-list", "--count", "HEAD"),
    name: `1.0.${git("rev-list", "--count", "HEAD")}-${git("rev-parse", "--short", "HEAD")}`,
  };
}

function build() {
  const config = readFrameConfig(join(here, "frame.config.json"));
  const webDist = join(here, "../frame-web/dist");
  if (!existsSync(join(webDist, "index.html"))) {
    throw new Error("Build packages/frame-web first (pnpm build runs it via turbo)");
  }
  rmSync(out, { recursive: true, force: true });
  const gen = join(out, "gen");
  const classes = join(out, "classes");
  const dex = join(out, "dex");
  const assets = join(out, "assets");
  for (const dir of [gen, classes, dex, assets]) mkdirSync(dir, { recursive: true });

  test();
  writeConfig(gen, config);
  run(java("javac"), [
    "-source",
    "8",
    "-target",
    "8",
    "-Xlint:-options",
    "-encoding",
    "UTF-8",
    "-classpath",
    ANDROID_JAR,
    "-d",
    classes,
    ...sources(join(here, "src")),
    ...sources(gen),
  ]);
  run(java("java"), [
    "-cp",
    join(TOOLS, "lib/d8.jar"),
    "com.android.tools.r8.D8",
    "--release",
    "--min-api",
    "26",
    "--lib",
    ANDROID_JAR,
    "--output",
    dex,
    ...readdirSync(classes, { recursive: true })
      .filter((f) => f.endsWith(".class"))
      .map((f) => join(classes, f)),
  ]);
  cpSync(webDist, join(assets, "web"), { recursive: true });

  const { code, name } = version();
  const resources = join(out, "res.zip");
  run(join(TOOLS, "aapt2"), ["compile", "--dir", join(here, "res"), "-o", resources]);
  const unsigned = join(out, "unsigned.apk");
  run(join(TOOLS, "aapt2"), [
    "link",
    resources,
    "-o",
    unsigned,
    "--manifest",
    join(here, "AndroidManifest.xml"),
    "-I",
    ANDROID_JAR,
    "-A",
    assets,
    "--version-code",
    code,
    "--version-name",
    name,
  ]);
  run("zip", ["-q", "-j", unsigned, join(dex, "classes.dex")]);
  const aligned = join(out, "aligned.apk");
  run(join(TOOLS, "zipalign"), ["-f", "-p", "4", unsigned, aligned]);

  const { ks, passFile } = keystore();
  const apk = join(out, "kids-dash-frame.apk");
  const apksigner = ["-jar", join(TOOLS, "lib/apksigner.jar")];
  run(java("java"), [
    ...apksigner,
    "sign",
    "--ks",
    ks,
    "--ks-pass",
    `file:${passFile}`,
    "--out",
    apk,
    aligned,
  ]);
  run(java("java"), [...apksigner, "verify", apk]);
  console.log(`built ${relative(root, apk)} (versionCode ${code}, ${name})`);
}

if (process.argv.includes("--test")) test();
else build();
